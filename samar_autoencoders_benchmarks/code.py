"""# Embedding Creation using AfriBERTa"""

def get_embedding(text, afri_tokenizer, afri_model):
    # Tokenize the text and convert it to tensor format
    inputs = afri_tokenizer(text, return_tensors="pt", truncation=True, padding=True, max_length=128)

    # Generate the output hidden states from AfriBERTa
    with torch.no_grad():
        outputs = afri_model(**inputs)

    # Get the embeddings by averaging the last hidden states (mean pooling)
    hidden_states = outputs.last_hidden_state
    embedding = hidden_states.mean(dim=1).squeeze().cpu().numpy()

    return embedding

